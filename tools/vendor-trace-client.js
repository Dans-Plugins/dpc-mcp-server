#!/usr/bin/env node
"use strict";

/**
 * Refresh the vendored usage-reporting client.
 *
 * The client is Stephenson-Software/trace-client-js, which is one TypeScript
 * file meant to be copied into a project. This server is plain CommonJS with no
 * build step and no runtime dependencies, and it stays that way, so the file is
 * vendored twice:
 *
 *   vendor/trace-client.ts   byte-for-byte what the client repo has at the pinned SHA
 *   vendor/trace-client.js   derived from it, and the copy the server loads
 *
 * The derivation is mechanical and has no dependency: Node's own
 * `module.stripTypeScriptTypes` erases the type annotations (it replaces them
 * with whitespace, which is why the derived file has odd gaps), the three
 * `export` keywords are dropped, and a `module.exports` line is appended.
 * Nothing else is touched, so the .js file is exactly as trustworthy as the .ts
 * file beside it, and the tests re-derive it to prove the two still agree.
 *
 *   npm run sync:trace-client                 # latest commit on the client's main
 *   npm run sync:trace-client -- --ref <sha>  # a specific commit
 *   npm run sync:trace-client -- --from ../trace-client-js
 *   npm run sync:trace-client -- --check      # does vendor/trace-client.js match the .ts?
 *
 * Like tools/sync.js, a branch is resolved to a commit SHA before anything is
 * fetched, and the SHA is recorded in vendor/TRACE_CLIENT.json.
 *
 * Deriving needs Node 22.13 or later (where `stripTypeScriptTypes` exists).
 * Running the server does not: the derived file is plain JavaScript that runs
 * on Node 18.
 */

const fs = require("fs");
const path = require("path");
const https = require("https");

const ROOT = path.join(__dirname, "..");
const VENDOR = path.join(ROOT, "vendor");
const REPO = "Stephenson-Software/trace-client-js";
const BRANCH = "main";
const REMOTE = "trace-client.ts";
const TS_FILE = path.join(VENDOR, "trace-client.ts");
const JS_FILE = path.join(VENDOR, "trace-client.js");
const SOURCE_FILE = path.join(VENDOR, "TRACE_CLIENT.json");
const EXPORTS = ["TRACE_CLIENT_VERSION", "TraceClient", "pagePath", "isBot"];

/** Whether this Node can derive the .js file at all. */
function canDerive() {
  return typeof require("module").stripTypeScriptTypes === "function";
}

/**
 * The .ts source as the CommonJS file the server loads. Deterministic, so the
 * tests can call it on the vendored .ts and compare with the vendored .js.
 */
function derive(ts, ref) {
  const { stripTypeScriptTypes } = require("module");
  // The API is marked experimental and says so on stderr; the output is what
  // is checked, so the warning is noise here.
  const emit = process.emitWarning;
  process.emitWarning = () => {};
  let js;
  try {
    js = stripTypeScriptTypes(ts, { mode: "strip" });
  } finally {
    process.emitWarning = emit;
  }
  const exported = [];
  js = js.replace(/^export (const|class|function) (\w+)/gm, (m, kind, name) => {
    exported.push(name);
    return `${kind} ${name}`;
  });
  if (exported.slice().sort().join() !== EXPORTS.slice().sort().join()) {
    throw new Error(`expected the client to export ${EXPORTS.join(", ")}, found ${exported.join(", ") || "nothing"}`);
  }
  if (/^\s*(export|import)\b/m.test(js)) {
    throw new Error("the client has an export or import this derivation does not handle");
  }
  js = js.split("\n").map((l) => l.replace(/\s+$/, "")).join("\n").replace(/\n{3,}/g, "\n\n").trim();
  return (
    "// GENERATED by tools/vendor-trace-client.js from vendor/trace-client.ts\n" +
    `// (${REPO} @ ${ref}). Do not edit; re-run the tool.\n` +
    '"use strict";\n\n' +
    js + "\n\n" +
    `module.exports = { ${EXPORTS.join(", ")} };\n`
  );
}

/** Refuse to vendor a client that does not load, or that sends without a key. */
function verify(js) {
  fs.mkdirSync(VENDOR, { recursive: true });
  const tmp = path.join(VENDOR, ".trace-client.check.js");
  fs.writeFileSync(tmp, js);
  try {
    const mod = require(tmp);
    for (const name of EXPORTS) if (!(name in mod)) throw new Error(`${name} is not exported`);
    const noKey = new mod.TraceClient("http://127.0.0.1:9", "check", {});
    if (noKey.enabled) throw new Error("a client with no key reports itself enabled");
    const off = new mod.TraceClient("http://127.0.0.1:9", "check", { key: "k", enabled: false });
    if (off.enabled) throw new Error("enabled: false does not disable the client");
    return mod.TRACE_CLIENT_VERSION;
  } finally {
    delete require.cache[require.resolve(tmp)];
    fs.unlinkSync(tmp);
  }
}

function get(url, headers) {
  return new Promise((resolve, reject) => {
    const opts = { headers: Object.assign({ "User-Agent": "dpc-mcp-server-sync" }, headers || {}) };
    https.get(url, opts, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        res.resume();
        return resolve(get(res.headers.location, headers));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`${url} returned HTTP ${res.statusCode}`));
      }
      let body = "";
      res.setEncoding("utf8");
      res.on("data", (c) => (body += c));
      res.on("end", () => resolve(body));
    }).on("error", reject);
  });
}

async function resolveRef(ref) {
  const body = await get(`https://api.github.com/repos/${REPO}/commits/${ref}`, {
    Accept: "application/vnd.github+json",
  });
  const sha = JSON.parse(body).sha;
  if (!/^[0-9a-f]{40}$/.test(sha || "")) throw new Error(`could not resolve ${ref} to a commit`);
  return sha;
}

function currentSource() {
  try { return JSON.parse(fs.readFileSync(SOURCE_FILE, "utf8")); } catch (e) { return null; }
}

async function main() {
  const argv = process.argv.slice(2);
  const at = (flag) => { const i = argv.indexOf(flag); return i !== -1 ? argv[i + 1] : null; };

  if (!canDerive()) {
    console.error(`error: deriving the client needs Node 22.13 or later (this is ${process.version})`);
    process.exit(2);
  }

  if (argv.includes("--check")) {
    const source = currentSource();
    if (!source) { console.error("no vendor/TRACE_CLIENT.json — run `npm run sync:trace-client`"); process.exit(1); }
    const want = derive(fs.readFileSync(TS_FILE, "utf8"), source.ref);
    if (fs.readFileSync(JS_FILE, "utf8") !== want) {
      console.error("vendor/trace-client.js does not match vendor/trace-client.ts — run `npm run sync:trace-client`");
      process.exit(1);
    }
    console.log(`vendor/trace-client.js matches vendor/trace-client.ts (${source.ref.slice(0, 10)})`);
    return;
  }

  const from = at("--from");
  let ts, ref, origin;
  try {
    if (from) {
      const { execFileSync } = require("child_process");
      ts = fs.readFileSync(path.join(from, REMOTE), "utf8");
      // A local checkout is only pinned if it is clean; otherwise the SHA would lie.
      const dirty = execFileSync("git", ["-C", from, "status", "--porcelain", "--", REMOTE], { encoding: "utf8" });
      if (dirty.trim()) throw new Error(`${REMOTE} has uncommitted changes in ${from}`);
      ref = execFileSync("git", ["-C", from, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
    } else {
      const wantRef = at("--ref") || BRANCH;
      ref = /^[0-9a-f]{40}$/.test(wantRef) ? wantRef : await resolveRef(wantRef);
      ts = await get(`https://raw.githubusercontent.com/${REPO}/${ref}/${REMOTE}`);
    }
    origin = `https://github.com/${REPO}`;
  } catch (e) {
    console.error(`error: ${e.message}`);
    process.exit(1);
  }

  let js, version;
  try {
    js = derive(ts, ref);
    version = verify(js);
  } catch (e) {
    console.error(`error: refusing to vendor a broken client — ${e.message}`);
    process.exit(1);
  }

  fs.writeFileSync(TS_FILE, ts);
  fs.writeFileSync(JS_FILE, js);
  fs.writeFileSync(SOURCE_FILE, JSON.stringify({
    repo: REPO,
    ref,
    origin,
    version,
    files: [REMOTE],
    derived: { "trace-client.js": "tools/vendor-trace-client.js (module.stripTypeScriptTypes, exports rewritten to CommonJS)" },
  }, null, 2) + "\n");
  console.log(`vendored trace-client ${version} from ${origin} @ ${ref.slice(0, 10)}`);
}

if (require.main === module) main();

module.exports = { derive, canDerive };
